"""Download the app's fonts (fontsource builds, latin + latin-ext for Polish) into
crates/app/assets/fonts/ and write crates/app/assets/fonts.css with their @font-face rules.

The fonts are committed; run this only to add or change one (`python scripts/fetch-fonts.py`).
The design's faces; a theme that needs another family adds it to FONTS.
"""

import pathlib
import sys
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent / "crates" / "app"
OUT = ROOT / "assets" / "fonts"
CSS = ROOT / "assets" / "fonts.css"
CDN = "https://cdn.jsdelivr.net/npm"

# (CSS family, fontsource package, variable?, [(weight, style), ...]). The design's faces:
# Old Standard TT (body), Special Elite (typewriter), Caveat (handwriting), Great Vibes (signatures).
FONTS = [
    ("Old Standard TT", "old-standard-tt", False, [("400", "normal"), ("700", "normal"), ("400", "italic")]),
    ("Special Elite", "special-elite", False, [("400", "normal")]),
    ("Caveat", "caveat", True, [("wght", "normal")]),
    ("Great Vibes", "great-vibes", False, [("400", "normal")]),  # signatures
]

# fontsource's ranges for the two subsets Polish text needs.
RANGES = {
    "latin": "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, "
    "U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
    "latin-ext": "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, "
    "U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, "
    "U+2113, U+2C60-2C7F, U+A720-A7FF",
}


def fetch(url: str) -> bytes | None:
    request = urllib.request.Request(url, headers={"User-Agent": "fetch-fonts"})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.read()
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    rules = ["/* Generated by scripts/fetch-fonts.py. */"]
    for family, package, variable, weights in FONTS:
        scope = "@fontsource-variable" if variable else "@fontsource"
        for weight, style in weights:
            for subset, unicode_range in RANGES.items():
                name = f"{package}-{subset}-{weight}-{style}.woff2"
                data = fetch(f"{CDN}/{scope}/{package}@5/files/{name}")
                if data is None:
                    print(f"  (no {subset} subset for {package} {weight})")
                    continue
                (OUT / name).write_bytes(data)
                css_weight = "100 900" if weight == "wght" else weight
                rules.append(
                    "@font-face {\n"
                    f"  font-family: '{family}';\n"
                    f"  font-style: {style};\n"
                    "  font-display: swap;\n"
                    f"  font-weight: {css_weight};\n"
                    f"  src: url('fonts/{name}') format('woff2');\n"
                    f"  unicode-range: {unicode_range};\n"
                    "}"
                )
                print(f"{name}: {len(data) // 1024} KiB")
    CSS.write_text("\n".join(rules) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
