"""Generate crates/app/src/components/icons.rs from Lucide (lucide-static on jsDelivr).

Each icon becomes a variant of `Icon`; the SVG keeps `class="lucide"` so themes can restyle every
icon at once (royal strokes them with the metal gradient). Add a name to ICONS and rerun:
`python scripts/fetch-icons.py`. The output is committed.
"""

import pathlib
import re
import sys
import urllib.request

LUCIDE = "https://cdn.jsdelivr.net/npm/lucide-static@0.469.0/icons"
OUT = pathlib.Path(__file__).resolve().parent.parent / "crates" / "app" / "src" / "components" / "icons.rs"

ICONS = [
    "vote",
    "handshake",
    "wallet",
    "gift",
    "log-out",
    "bell",
    "bell-off",
    "palette",
    "refresh-cw",
    "download",
    "chevron-left",
    "shield",
    "loader-circle",
    "wifi-off",
    "circle-alert",
    "x",
    "check",
    "user",
]


def variant(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("-"))


def main() -> int:
    arms = []
    for name in ICONS:
        request = urllib.request.Request(f"{LUCIDE}/{name}.svg", headers={"User-Agent": "fetch-icons"})
        with urllib.request.urlopen(request, timeout=60) as response:
            svg = response.read().decode("utf-8")
        inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
        if inner is None:
            raise SystemExit(f"unexpected SVG for {name}")
        body = re.sub(r"\s+", " ", inner.group(1)).strip()
        body = body.replace("> <", "><")
        arms.append(f'            Self::{variant(name)} => r#"{body}"#,')
    variants = "\n".join(f"    {variant(name)}," for name in ICONS)
    names = "\n".join(arms)
    OUT.write_text(
        f"""//! Lucide icons (ISC license), generated by `scripts/fetch-icons.py`; do not edit.

use dioxus::prelude::*;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Icon {{
{variants}
}}

impl Icon {{
    fn body(self) -> &'static str {{
        match self {{
{names}
        }}
    }}
}}

/// An icon at `size` px, stroked with `currentColor` (themes may override via `.lucide`).
#[component]
pub fn Svg(icon: Icon, #[props(default = 24)] size: u32, #[props(default)] class: String) -> Element {{
    rsx! {{
        svg {{
            class: "lucide {{class}}",
            xmlns: "http://www.w3.org/2000/svg",
            width: "{{size}}",
            height: "{{size}}",
            view_box: "0 0 24 24",
            fill: "none",
            stroke: "currentColor",
            stroke_width: "2",
            stroke_linecap: "round",
            stroke_linejoin: "round",
            "aria-hidden": "true",
            dangerous_inner_html: icon.body(),
        }}
    }}
}}
""",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{len(ICONS)} icons -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
