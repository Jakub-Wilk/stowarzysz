-- Secret Santa. While an event is active a pairing exists only sealed (XChaCha20-Poly1305 with
-- the event, giver and tier as associated data); ending the event reveals it into `receiver_id`.

create table santa_events (
    id         bigint generated by default as identity primary key,
    status     text        not null default 'active' check (status in ('active', 'ended')),
    mode       text        not null default 'single' check (mode in ('single', 'per_tier')),
    deadline   timestamptz not null, -- informational; a superuser ends the event by hand
    gift_tiers bigint[]    not null check (cardinality(gift_tiers) between 1 and 10),
    created_by bigint      not null references users on delete restrict,
    created_at timestamptz not null default now(),
    ended_at   timestamptz,
    constraint santa_events_ended check ((status = 'ended') = (ended_at is not null))
);
create unique index santa_events_single_active on santa_events ((true)) where status = 'active';

create table santa_assignments (
    id          bigint generated by default as identity primary key,
    event_id    bigint   not null references santa_events on delete cascade,
    giver_id    bigint   not null references users on delete restrict,
    -- Position in `gift_tiers` (0 = highest); NULL when one victim gets every tier.
    tier_index  smallint check (tier_index >= 0),
    sealed      bytea,   -- while the event is active
    receiver_id bigint   references users on delete restrict, -- once it has ended
    constraint santa_assignments_sealed_or_revealed check ((sealed is null) = (receiver_id is not null)),
    constraint santa_assignments_unique unique nulls not distinct (event_id, giver_id, tier_index)
);
create index santa_assignments_giver on santa_assignments (giver_id);

-- What was given for one tier of one pairing; snapshotted when the event ends.
create table santa_gifts (
    id            bigint generated by default as identity primary key,
    assignment_id bigint not null references santa_assignments on delete cascade,
    amount        bigint not null check (amount > 0),
    note          text   not null default '',
    constraint santa_gifts_unique unique (assignment_id, amount)
);

-- A giver asking their victim, anonymously, for ideas. It names the receiver and tier, never
-- the giver: that pair identifies the pairing without writing it down in plain text.
create table santa_help_requests (
    id          bigint generated by default as identity primary key,
    event_id    bigint      not null references santa_events on delete cascade,
    receiver_id bigint      not null references users on delete restrict,
    tier_index  smallint    check (tier_index >= 0),
    ideas       text[]      not null default '{}',
    asked_at    timestamptz not null,
    answered_at timestamptz, -- cleared when the giver asks again
    constraint santa_help_requests_unique unique nulls not distinct (event_id, receiver_id, tier_index)
);
