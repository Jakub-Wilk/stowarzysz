-- Kasa Skarbowa. An entry is what happened; its obligations are who owes whom because of it;
-- balances aggregate the obligations of confirmed entries. Amounts are bigint minor units.

create table ledger_entries (
    id          bigint generated by default as identity primary key,
    kind        text            not null check (kind in ('expense', 'income', 'debt', 'payment')),
    status      text            not null default 'confirmed' check (status in (
        'pending', 'confirmed', 'rejected', 'cancelled')),
    title       text            not null,
    note        text            not null default '',
    category    text            not null default '' check (category in (
        '', 'lodging', 'bills', 'groceries', 'fun', 'health', 'insurance', 'transport',
        'food', 'shopping', 'weed', 'other')),
    occurred_on date            not null,
    amount      bigint          check (amount > 0),       -- minor units of `currency`, or a quantity of `item`
    currency    text            not null default '',
    item        text            not null default '',
    base_amount bigint          check (base_amount >= 0), -- `amount` in PLN grosze
    rate        numeric(20, 10),                          -- NULL: base currency
    rate_date   date,
    details     jsonb           not null default '{}',    -- typed per kind in the domain crate
    -- manual: recorded by a member; pact: a pact settlement (`pact_id`); tricount: imported
    -- (`source_ref` is the Tricount id); legacy: a debt from before sources existed (read-only).
    source      text            not null default 'manual' check (source in (
        'manual', 'pact', 'tricount', 'legacy')),
    source_ref  bigint,
    pact_id     bigint          references pacts on delete restrict,
    created_by  bigint          references users on delete restrict, -- NULL: recorded by the system
    updated_by  bigint          references users on delete restrict,
    created_at  timestamptz     not null default now(),
    updated_at  timestamptz     not null default now(),
    version     integer         not null default 1 check (version > 0),
    decided_at  timestamptz,
    constraint ledger_entries_pact_source check (pact_id is null or source = 'pact')
);
create index ledger_entries_feed on ledger_entries (occurred_on desc, id desc);
create index ledger_entries_kind_status on ledger_entries (status, kind);
create index ledger_entries_pact on ledger_entries (pact_id) where pact_id is not null;

create table ledger_obligations (
    id          bigint generated by default as identity primary key,
    entry_id    bigint not null references ledger_entries on delete cascade,
    debtor_id   bigint not null references users on delete restrict,
    creditor_id bigint not null references users on delete restrict,
    amount      bigint not null check (amount > 0),
    item        text   not null default '', -- empty: PLN grosze; else a quantity of goods
    constraint ledger_obligations_distinct_parties check (debtor_id <> creditor_id)
);
create index ledger_obligations_entry on ledger_obligations (entry_id);

-- Per-person paid/owed of an expense or income, materialised at write time so breakdowns and
-- statistics are plain SQL aggregates.
create table ledger_entry_shares (
    entry_id  bigint not null references ledger_entries on delete cascade,
    user_id   bigint not null references users on delete restrict,
    paid      bigint not null check (paid >= 0),      -- entry currency
    owed      bigint not null check (owed >= 0),
    paid_base bigint not null check (paid_base >= 0), -- PLN grosze
    owed_base bigint not null check (owed_base >= 0),
    primary key (entry_id, user_id)
);
create index ledger_entry_shares_user on ledger_entry_shares (user_id);

create table ledger_attachments (
    id          bigint generated by default as identity primary key,
    entry_id    bigint      not null references ledger_entries on delete cascade,
    uploaded_by bigint      not null references users on delete restrict,
    image_key   text        not null unique,
    width       integer     not null check (width > 0),
    height      integer     not null check (height > 0),
    created_at  timestamptz not null default now()
);
create index ledger_attachments_entry on ledger_attachments (entry_id);

-- ECB rates (via Frankfurter): one unit of `currency` in PLN on `requested_on`, as published on
-- `rate_date`. Never changes once stored.
create table exchange_rates (
    currency     text            not null,
    requested_on date            not null,
    rate         numeric(20, 10) not null check (rate > 0),
    rate_date    date            not null,
    primary key (currency, requested_on)
);
