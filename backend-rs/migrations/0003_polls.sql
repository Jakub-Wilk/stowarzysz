-- Sejmik: votes. Everything kind-specific (config, ballot and result shapes) is typed in the
-- `domain` crate and stored as JSON, so a new kind needs a variant and no new tables.

create table polls (
    id                 bigint generated by default as identity primary key,
    creator_id         bigint      not null references users on delete restrict,
    title              text        not null,
    kind               text        not null check (kind in (
        'score', 'nickname', 'avatar', 'pact_ruling', 'resolution_judgment',
        'single_choice', 'multi_choice', 'ranked_choice')),
    config             jsonb       not null default '{}',
    status             text        not null default 'open' check (status in ('open', 'closed')),
    close_reason       text        check (close_reason in ('auto', 'creator', 'expired')),
    result             jsonb,      -- computed once at close, then frozen
    created_at         timestamptz not null default now(),
    -- Every poll ends at a fixed deadline; reminders go to non-voters before it.
    deadline_at        timestamptz not null,
    next_reminder_at   timestamptz,
    reminders_sent     smallint    not null default 0 check (reminders_sent >= 0),
    closed_at          timestamptz,
    -- Avatar votes: the proposed picture, and the target's picture it replaced (for the record).
    proposed_image_key text,
    previous_image_key text,
    -- A follow-up vote between the options an option poll tied on; at most one per poll.
    tie_break_of       bigint      unique references polls on delete restrict,
    -- What the vote decides, by kind (the FKs to pacts are added in 0004_pacts.sql). Only
    -- imported history whose subject no longer exists may leave them NULL.
    subject_user_id    bigint      references users on delete restrict,
    subject_claim_id   bigint      unique,
    subject_pact_id    bigint,
    constraint polls_closed_consistent check (
        (status = 'closed') = (closed_at is not null and close_reason is not null and result is not null)),
    constraint polls_subject_user_kind check (subject_user_id is null or kind in ('nickname', 'avatar')),
    constraint polls_subject_claim_kind check (subject_claim_id is null or kind = 'pact_ruling'),
    constraint polls_subject_pact_kind check (subject_pact_id is null or kind = 'resolution_judgment')
);
create index polls_feed on polls (status, created_at desc, id desc);
create index polls_due on polls (least(deadline_at, coalesce(next_reminder_at, deadline_at)))
    where status = 'open';
create index polls_subject_pact on polls (subject_pact_id) where subject_pact_id is not null;

create table poll_participants (
    poll_id       bigint      not null references polls on delete cascade,
    user_id       bigint      not null references users on delete restrict,
    ballot        jsonb,      -- shape defined by the poll's kind; hidden until the poll ends
    vetoed        boolean     not null default false,
    abstained     boolean     not null default false,
    reason        text        not null default '', -- for a veto or an abstention
    voted_at      timestamptz,                     -- NULL also for someone auto-abstained at close
    last_reaction text        not null default '',
    primary key (poll_id, user_id),
    constraint poll_participants_veto_or_abstain check (not (vetoed and abstained))
);
create index poll_participants_user on poll_participants (user_id);
