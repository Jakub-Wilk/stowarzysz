-- People, account activation and login sessions.
--
-- Conventions for every table: bigint identity keys (BY DEFAULT, so the Django importer can keep
-- the old ids, which JSON columns refer to), timestamptz everywhere, enums as text + CHECK, and
-- foreign keys to users RESTRICT from history tables: an account with history is deactivated,
-- never deleted, so nobody else's records change under them.

create table users (
    id                   bigint generated by default as identity primary key,
    username             text        not null,
    -- PHC string (argon2id), or a legacy Django `pbkdf2_sha256$...` until the next login.
    -- NULL: the account was created by an admin and is not activated yet.
    password_hash        text,
    is_active            boolean     not null default true,
    is_superuser         boolean     not null default false,
    -- Media key of the profile picture (`avatars/<uuid>`); see 0002_media.sql.
    avatar_key           text,
    birthday             date,
    -- The day the birthday push last went out (the job runs often, the push once).
    birthday_reminded_on date,
    created_at           timestamptz not null default now(),
    constraint users_username_unique unique (username),
    constraint users_username_not_blank check (btrim(username) <> '')
);

-- Members: the people who can take part in things.
create index users_members on users (username) where is_active and password_hash is not null;

-- One-time links that let an admin-created account set its own password.
create table activation_tokens (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null references users on delete cascade,
    token_hash bytea       not null unique, -- SHA-256 of the raw token; the raw value is shown once
    created_by bigint      references users on delete set null,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null,
    used_at    timestamptz
);
create index activation_tokens_open on activation_tokens (user_id) where used_at is null;

-- A signed-in device. The refresh token is opaque and stored hashed; it rotates on every
-- refresh, but the previous one stays valid until the client has used the new one (a PWA killed
-- between receiving and storing a rotated token must not be logged out). Sliding expiry, no cap.
create table auth_sessions (
    id                uuid        primary key,
    user_id           bigint      not null references users on delete cascade,
    refresh_hash      bytea       not null unique,
    prev_refresh_hash bytea       unique,
    user_agent        text        not null default '',
    created_at        timestamptz not null default now(),
    last_used_at      timestamptz not null default now(),
    expires_at        timestamptz not null,
    revoked_at        timestamptz
);
create index auth_sessions_live on auth_sessions (user_id) where revoked_at is null;
create index auth_sessions_expiry on auth_sessions (expires_at);

-- SimpleJWT refresh tokens imported from the Django backend, each exchangeable once for a
-- session so nobody is logged out by the migration.
create table legacy_refresh_tokens (
    jti        text        primary key,
    user_id    bigint      not null references users on delete cascade,
    expires_at timestamptz not null
);
create index legacy_refresh_tokens_expiry on legacy_refresh_tokens (expires_at);
