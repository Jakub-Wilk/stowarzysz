-- Umowy: bets, group bets, resolutions and shared goals. Money never lives here: settling hands
-- debts to the ledger (`ledger_entries.pact_id`).

create table pacts (
    id               bigint generated by default as identity primary key,
    creator_id       bigint      not null references users on delete restrict,
    kind             text        not null check (kind in ('bet', 'group_bet', 'resolution', 'shared_goal')),
    title            text        not null,
    condition        text        not null,
    notes            text        not null default '',
    due_at           timestamptz,
    config           jsonb       not null default '{}',
    status           text        not null default 'proposed' check (status in (
        'proposed', 'active', 'awaiting_result', 'resolved', 'cancelled', 'void')),
    created_at       timestamptz not null default now(),
    resolved_at      timestamptz,
    -- When the scheduler next acts on it: the deadline (a proposed pact lapses, an active one
    -- becomes overdue), then weekly "please settle this" nudges while awaiting a result.
    next_nudge_at    timestamptz,
    -- The resolution_judgment vote currently running, if any (one at a time).
    judgment_poll_id bigint      unique references polls on delete set null
);
create index pacts_feed on pacts (status, created_at desc, id desc);
create index pacts_due on pacts (next_nudge_at)
    where status in ('proposed', 'active', 'awaiting_result') and next_nudge_at is not null;

create table pact_participants (
    id           bigint generated by default as identity primary key,
    pact_id      bigint      not null references pacts on delete cascade,
    user_id      bigint      not null references users on delete restrict,
    role         text        not null default 'opponent' check (role in ('host', 'opponent')),
    side         text        not null default '',
    stake_amount bigint      check (stake_amount > 0), -- grosze
    stake_note   text        not null default '',      -- a stake in kind, e.g. "kolacja"
    state        text        not null default 'invited' check (state in (
        'invited', 'requested', 'active', 'settled', 'void',
        'declined', 'rejected', 'withdrawn', 'expired')),
    created_at   timestamptz not null default now(),   -- reset when a join request is re-sent
    expires_at   timestamptz,                          -- when an unanswered invite/request lapses
    constraint pact_participants_unique unique (pact_id, user_id),
    constraint pact_participants_pact_key unique (pact_id, id) -- target of composite FKs
);
create unique index pact_participants_single_host on pact_participants (pact_id) where role = 'host';
create index pact_participants_user on pact_participants (user_id);
create index pact_participants_expiry on pact_participants (expires_at)
    where state in ('invited', 'requested');

-- Outcome claims. `wager_id` scopes a claim to one wager of a bet (NULL: the whole pact); the
-- composite FK guarantees the wager belongs to the same pact.
create table pact_claims (
    id          bigint generated by default as identity primary key,
    pact_id     bigint      not null references pacts on delete cascade,
    wager_id    bigint,
    proposed_by bigint      not null references users on delete restrict,
    result      jsonb       not null,
    state       text        not null default 'pending' check (state in (
        'pending', 'confirmed', 'disputed', 'superseded', 'overruled')),
    created_at  timestamptz not null default now(),
    decided_at  timestamptz,
    constraint pact_claims_wager_fk foreign key (pact_id, wager_id)
        references pact_participants (pact_id, id) on delete cascade
);
-- At most one live (pending or disputed) claim per pact or wager.
create unique index pact_claims_one_live on pact_claims (pact_id, wager_id) nulls not distinct
    where state in ('pending', 'disputed');

create table pact_claim_confirmations (
    claim_id   bigint      not null references pact_claims on delete cascade,
    user_id    bigint      not null references users on delete restrict,
    created_at timestamptz not null default now(),
    primary key (claim_id, user_id)
);

-- Who won what, recorded when a claim is confirmed.
create table pact_verdicts (
    claim_id bigint not null references pact_claims on delete cascade,
    user_id  bigint not null references users on delete restrict,
    verdict  text   not null check (verdict in ('won', 'lost', 'draw', 'void')),
    primary key (claim_id, user_id)
);
create index pact_verdicts_user on pact_verdicts (user_id);

create table pact_join_consents (
    participant_id bigint  not null references pact_participants on delete cascade,
    approver_id    bigint  not null references users on delete restrict,
    approved       boolean, -- NULL until they decide
    primary key (participant_id, approver_id)
);
create index pact_join_consents_open on pact_join_consents (approver_id) where approved is null;

create table pact_attachments (
    id          bigint generated by default as identity primary key,
    pact_id     bigint      not null references pacts on delete cascade,
    uploaded_by bigint      not null references users on delete restrict,
    image_key   text        not null unique,
    width       integer     not null check (width > 0),
    height      integer     not null check (height > 0),
    caption     text        not null default '',
    created_at  timestamptz not null default now()
);
create index pact_attachments_pact on pact_attachments (pact_id);

-- Polls that decide pacts (declared in 0003_polls.sql).
alter table polls
    add constraint polls_subject_claim_fk foreign key (subject_claim_id)
        references pact_claims on delete restrict,
    add constraint polls_subject_pact_fk foreign key (subject_pact_id)
        references pacts on delete restrict;
