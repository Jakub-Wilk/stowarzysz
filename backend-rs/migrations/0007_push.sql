-- Web Push. Notifications go through a transactional outbox: one row per subscription, written
-- in the transaction that caused it, delivered (with retries) by a worker after commit.

create table push_subscriptions (
    id              bigint generated by default as identity primary key,
    user_id         bigint      not null references users on delete cascade,
    -- Identifies a browser; it follows whoever registered it last.
    endpoint        text        not null unique,
    p256dh          text        not null,
    auth            text        not null,
    user_agent      text        not null default '',
    created_at      timestamptz not null default now(),
    last_success_at timestamptz,
    failure_count   integer     not null default 0
);
create index push_subscriptions_user on push_subscriptions (user_id);

create table push_outbox (
    id              bigint generated by default as identity primary key,
    subscription_id bigint      not null references push_subscriptions on delete cascade,
    payload         jsonb       not null, -- {title, body, url}
    created_at      timestamptz not null default now(),
    attempts        smallint    not null default 0,
    next_attempt_at timestamptz not null default now(),
    expires_at      timestamptz not null  -- a notification is worthless after its TTL
);
create index push_outbox_due on push_outbox (next_attempt_at);
